import type { ScaffoldLessonsResult } from '../lessons/init.js';

export type CommandResult =
  | { success: true; data: unknown }
  | { success: false; error: string; data?: unknown };

export interface GenerateData {
  scope: 'project' | 'global';
  mode: 'generate' | 'check' | 'dry-run';
  files: Array<{ path: string; target: string; status: 'created' | 'updated' | 'unchanged' }>;
  summary: { created: number; updated: number; unchanged: number };
  /**
   * Why zero files were produced, when known. `no-global-support` means every
   * active target lacks a global layout (e.g. cloud-only jules/replit-agent in
   * `--global`); the renderer surfaces that instead of the misleading default
   * "no root rule / rules feature disabled" cause. Absent when files exist or
   * the cause is the default one.
   */
  emptyReason?: 'no-global-support';
}

export interface InitData {
  scope: 'project' | 'global';
  configFile: string;
  localConfigFile: string;
  detectedConfigs: string[];
  /** Target IDs written to agentsmesh.yaml. */
  targets: string[];
  /** Which rule picked `targets`: explicit flag, detection, or the minimal fallback. */
  targetSource: 'explicit' | 'all' | 'project' | 'machine' | 'fallback';
  imported: Array<{ from: string; to: string }>;
  importedToolCount: number;
  /** Two or more detected tools' root rules were combined into one canonical root. */
  rootRuleMerged: boolean;
  /**
   * Rules, commands or agents two tools both had, with different text. The
   * earlier tool's file kept its name; the later tool's text was saved as `copy`.
   */
  sameNameCopies: Array<{ path: string; copy: string; tool: string }>;
  scaffoldType: 'full' | 'gap-fill' | 'none';
  gitignoreUpdated: boolean;
  /**
   * Populated when --lessons is passed; absent otherwise. The scaffold's own
   * result type is the single source of truth — do not re-declare the shape here.
   */
  lessons?: ScaffoldLessonsResult;
  /**
   * True when --lessons was passed against an already-initialized project,
   * meaning init only scaffolded the lessons subsystem (config + scaffold
   * were left untouched).
   */
  lessonsOnly?: boolean;
  /**
   * True when the interactive wizard was cancelled (Ctrl-C). Nothing was
   * written; every other field carries its empty/none value.
   */
  cancelled?: boolean;
}

export interface ImportData {
  scope: 'project' | 'global';
  target: string;
  files: Array<{ from: string; to: string }>;
  /** This target's root rule accumulated onto one already in the canonical root. */
  rootRuleMerged: boolean;
}

export interface DiffData {
  files: Array<{ path: string; target: string; status: 'created' | 'updated' | 'deleted' }>;
  patches: Array<{ path: string; patch: string }>;
  summary: { created: number; updated: number; unchanged: number; deleted: number };
}

export interface LintData {
  diagnostics: Array<{ level: 'error' | 'warning'; file: string; target: string; message: string }>;
  summary: { errors: number; warnings: number };
}

export interface CheckData {
  hasLock: boolean;
  /** True when the lock file has git conflict markers; `agentsmesh merge` rebuilds it. */
  lockConflict: boolean;
  /** True when canonical files or extends differ from the lock. */
  canonicalDrift: boolean;
  /** True when a generated output is modified, removed, or stale. */
  outputDrift: boolean;
  inSync: boolean;
  modified: string[];
  added: string[];
  removed: string[];
  extendsModified: string[];
  lockedViolations: string[];
  /** Generated outputs whose on-disk hash differs from the lock. */
  outputsModified: string[];
  /** Generated outputs recorded in the lock but missing from disk. */
  outputsRemoved: string[];
  /** Managed generated outputs present on disk but absent from the lock. */
  outputsStale: string[];
  /** Targets a `generate --targets` run left out after canonical sources changed. */
  staleTargets: string[];
  /** Managed-dir files agentsmesh did not write; informational, never drift. */
  outputsUntracked: string[];
  /**
   * True when generated-output drift was actually verified. False for
   * old-format locks (no `outputs` map) or when `--no-outputs` was passed;
   * the renderer surfaces an informational note in that case.
   */
  outputsChecked: boolean;
}

export interface MergeData {
  hadConflict: boolean;
  resolved: boolean;
}

export interface MatrixData {
  targets: string[];
  features: Array<{ name: string; support: Record<string, string> }>;
}

export interface InstallBrokenResource {
  /** Source file or skill-directory path that was skipped during install. */
  path: string;
  /** Why it was skipped: invalid YAML, unparseable SKILL.md, etc. */
  kind: 'frontmatter' | 'skill-dir' | 'unsupported-extension';
  /** Human-readable cause; typically the underlying YAML or filesystem error. */
  reason: string;
}

export interface InstallSubPackFailure {
  /** Sub-pack name as generated by the picker (`<source>-<slug>`). */
  name: string;
  /** Sub-pack path inside the source repo (e.g. `plugins/team`). */
  path: string;
  /** Error message from the failed sub-pack install. */
  error: string;
}

export interface InstallData {
  source: string;
  mode: 'install' | 'sync';
  installed: Array<{ kind: string; name: string; path: string }>;
  skipped: Array<{ kind: string; name: string; reason: string }>;
  dryRun: boolean;
  /**
   * Files the install pipeline skipped because their YAML frontmatter (or
   * SKILL.md) could not be parsed. Absent when nothing was skipped. The CLI
   * renderer surfaces a footer warning when this is present.
   */
  brokenResources?: InstallBrokenResource[];
  /**
   * Marketplace sub-packs that threw during install. Only set when the
   * marketplace dispatcher catches per-target failures; absent for
   * single-pack installs. Renderer prints a per-failure warning so partial
   * marketplace installs are never silent.
   */
  subPackFailures?: InstallSubPackFailure[];
}

export interface UninstallRemovedEntry {
  name: string;
  /**
   * Forward-slash relative path to the pack directory, or `null` for
   * extends-only installs (`install --extends`) that never materialized
   * a pack on disk.
   */
  pack_path: string | null;
  manifest_entry_removed: boolean;
  extends_entry_removed: boolean;
  generated_files_removed: number;
  modified_files_kept: Array<{ relativePath: string; status: string }>;
  legacy_migrated: boolean;
  /**
   * True when at least one expected removal step did not land (pack bytes
   * preserved via `[k]eep-modified` or `--keep-pack`, missing extends row,
   * etc.). Lets JSON consumers distinguish a fully-clean run from a
   * deliberately-or-silently partial one.
   */
  partial: boolean;
}

export interface UninstallData {
  scope: 'project' | 'global';
  mode: 'uninstall';
  removed: UninstallRemovedEntry[];
  skipped: Array<{ name: string; reason: string }>;
  /**
   * Packs whose `applyUninstall` threw mid-batch. Surviving packs continue;
   * post-operation `generate` still runs over the packs that did apply so the
   * tool tree is consistent with `installs.yaml` after the partial run.
   */
  failed: Array<{ name: string; reason: string }>;
  dryRun: boolean;
}

export interface InstallsListEntry {
  name: string;
  source: string;
  source_kind: string;
  /** Classifier verdict captured at install time, or `null` when unknown. */
  source_type: string | null;
  version: string | null;
  features: string[];
  target: string | null;
  /** ISO timestamp from the pack install-manifest, or `null` when missing. */
  installed_at: string | null;
  /** ISO timestamp from the last `agentsmesh refresh`, or `null` when never refreshed. */
  refreshed_at: string | null;
  /** Forward-slash relative path from the canonical scope root. */
  pack_path: string;
  /**
   * SPDX identifier detected from the pack's LICENSE/NOTICE/COPYING file at
   * install time, or `null` when no license file is present in the pack root
   * (and `null` when the text matches no known fingerprint). Surfacing this
   * lets the user spot proprietary or unknown-terms upstreams at a glance.
   */
  license: string | null;
}

export interface InstallsListData {
  scope: 'project' | 'global';
  subcommand: 'list';
  installs: InstallsListEntry[];
}

export interface PluginAddData {
  subcommand: 'add';
  id: string;
  package: string;
  version: string;
}

export interface PluginListData {
  subcommand: 'list';
  plugins: Array<{
    id: string;
    package: string;
    version?: string;
    status?: string;
    targets?: string;
  }>;
}

export interface PluginRemoveData {
  subcommand: 'remove';
  id: string;
  found: boolean;
}

export interface PluginInfoData {
  subcommand: 'info';
  id: string;
  package: string;
  version?: string;
  descriptors: Array<{ id: string; description: string }>;
}

export type PluginData = PluginAddData | PluginListData | PluginRemoveData | PluginInfoData;

export interface TargetData {
  id: string;
  written: string[];
  skipped: string[];
  postSteps: string[];
}

export interface ConvertData {
  from: string;
  to: string;
  mode: 'convert' | 'dry-run';
  files: Array<{ path: string; target: string; status: 'created' | 'updated' | 'unchanged' }>;
  summary: { created: number; updated: number; unchanged: number };
}

export type FailurePhase = 'plan' | 'fetch' | 'apply' | 'manifest-update';

export interface RefreshData {
  scope: 'project' | 'global';
  mode: 'refresh';
  refreshed: Array<{
    name: string;
    oldRef: string | null;
    newRef: string;
    oldSha: string | null;
    newSha: string;
    changedFiles: { added: string[]; removed: string[]; modified: string[] };
  }>;
  unchanged: Array<{ name: string; ref: string }>;
  skipped: Array<{ name: string; reason: 'user-declined' }>;
  failed: Array<{
    name: string;
    phase: FailurePhase;
    error: string;
  }>;
  dryRun: boolean;
}
